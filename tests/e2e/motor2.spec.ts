import { expect, test } from '@playwright/test'
import { acceptProposal, collectErrors, countSessions, onboard } from './helpers'

test('A16/F8 · 20,5, cambiar repeticiones y RIR, marcar, escribir nota y recargar al instante conserva todo', async ({ page }) => {
  const errors = collectErrors(page)
  await onboard(page)
  await acceptProposal(page)
  await page.getByRole('button', { name: /^Empezar$/ }).click()
  for (let run = 0; run < 3; run++) {
    const ex = page.locator('section.wk-ex').first()
    await ex.getByRole('textbox', { name: 'kg de la máquina, serie 1' }).fill('20,5')
    await ex.getByRole('textbox', { name: 'Repeticiones, serie 1' }).fill('9')
    await ex.getByRole('textbox', { name: 'Repeticiones, serie 1' }).fill('11')
    await ex.getByRole('button', { name: /^RIR serie 1:/ }).click()
    await page.getByRole('dialog').getByRole('button', { name: '2', exact: true }).click()
    const mark = ex.getByRole('button', { name: 'Marcar serie 1 como hecha' })
    if (await mark.count()) await mark.click()
    const note = ex.getByRole('textbox', { name: /^Notas de / })
    if (!(await note.count())) await ex.getByRole('button', { name: 'Nota', exact: true }).click()
    await ex.getByRole('textbox', { name: /^Notas de / }).fill('')
    await ex.getByRole('textbox', { name: /^Notas de / }).pressSequentially(`agarre neutro ${run}`, { delay: 5 })
    await page.reload()
    const ex2 = page.locator('section.wk-ex').first()
    await expect(ex2.getByRole('textbox', { name: 'kg de la máquina, serie 1' })).toHaveValue('20,5')
    await expect(ex2.getByRole('textbox', { name: 'Repeticiones, serie 1' })).toHaveValue('11')
    await expect(ex2.getByRole('button', { name: 'RIR serie 1: 2' })).toBeVisible()
    await expect(ex2.getByRole('button', { name: 'Desmarcar serie 1' })).toBeVisible()
    await expect(ex2.getByRole('textbox', { name: /^Notas de / })).toHaveValue(`agarre neutro ${run}`)
  }
  // Doble toque: no marca y desmarca a la vez
  const ex = page.locator('section.wk-ex').nth(1)
  await ex.getByRole('button', { name: /^Marcar serie 1 como hecha$/ }).dblclick()
  await expect(ex.getByRole('button', { name: 'Desmarcar serie 1' })).toBeVisible()
  expect(await countSessions(page)).toBe(1)
  expect(errors).toEqual([])
})

test('A15 · una parcial aparece primero en Hoy; retomar no duplica; repetir propone el mismo día', async ({ page }) => {
  await onboard(page)
  await acceptProposal(page)
  await page.getByRole('button', { name: /^Empezar$/ }).click()
  const ex = page.locator('section.wk-ex').first()
  await ex.getByRole('textbox', { name: 'kg de la máquina, serie 1' }).fill('30')
  await ex.getByRole('textbox', { name: 'Repeticiones, serie 1' }).fill('10')
  await ex.getByRole('button', { name: 'Marcar serie 1 como hecha' }).click()
  await page.getByRole('button', { name: 'Terminar' }).click()
  await page.getByRole('button', { name: 'Guardar como parcial' }).click()
  await expect(page.getByText('Sesión parcial: ¿qué prefieres?')).toBeVisible()
  await page.goto('/#/hoy')
  const card = page.getByRole('region', { name: 'Sesión parcial' })
  await expect(card).toBeVisible()
  await expect(card.getByText(/Hiciste 1 de \d+ series de trabajo/)).toBeVisible()
  await card.getByRole('button', { name: 'Retomar lo pendiente' }).click()
  await expect(page.getByRole('button', { name: 'Terminar' })).toBeVisible()
  await expect(page.locator('section.wk-ex').first().getByRole('button', { name: 'Desmarcar serie 1' })).toBeVisible()
  expect(await countSessions(page)).toBe(1)
  expect(await countSessions(page, 'active')).toBe(1)
  await page.getByRole('button', { name: 'Terminar' }).click()
  await page.getByRole('button', { name: 'Guardar como parcial' }).click()
  await page.getByRole('button', { name: 'Repetir esta sesión otro día' }).click()
  await page.goto('/#/hoy')
  await expect(page.getByRole('region', { name: 'Sesión parcial' })).toHaveCount(0)
  await expect(page.locator('.hero-day').first()).toHaveText(/Día A/)
  expect(await countSessions(page)).toBe(1)
})

test('A18 · la ficha abre arriba con título y demostración; al volver, la lista recupera su posición', async ({ page }) => {
  await onboard(page)
  await acceptProposal(page)
  await page.goto('/#/ejercicios')
  await expect(page.getByRole('heading', { name: 'Ejercicios' })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 2200))
  await page.waitForTimeout(200)
  const before = await page.evaluate(() => window.scrollY)
  expect(before).toBeGreaterThan(1500)
  const link = page.locator('a.list-item').filter({ hasText: /./ }).nth(30)
  const name = (await link.locator('span[style*="font-weight"]').first().textContent())!.trim()
  await link.scrollIntoViewIfNeeded()
  const listY = await page.evaluate(() => window.scrollY)
  await link.click()
  await expect(page.getByRole('heading', { level: 1, name })).toBeInViewport()
  expect(await page.evaluate(() => window.scrollY)).toBeLessThan(10)
  await page.getByRole('button', { name: 'Volver' }).click()
  await expect(page.getByRole('heading', { name: 'Ejercicios' })).toBeAttached()
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(listY - 60)
})

